def _insert(conn, table, columns, values):
    ph = ", ".join("?" for _ in columns)
    conn.execute(f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({ph})", values)


def seed(conn):
    # Одна транзакция: запущенный бэкенд видит либо старую базу, либо новую — без пустых таблиц
    conn.execute("BEGIN IMMEDIATE")
    for t in ("visual_result", "inspection", "parameter", "component", "equipment"):
        conn.execute(f"DROP TABLE IF EXISTS {t}")
    db.create_schema(conn)
    for e in EQUIPMENT:
        _insert(conn, "equipment", list(e), list(e.values()))
    for c in COMPONENTS:
        _insert(conn, "component", _C, c)
    for p in PARAMETERS:
        _insert(conn, "parameter", _P, p)
    for v in VISUAL_RESULTS:
        _insert(conn, "visual_result", _V, v)
    for i in INSPECTIONS:
        i = list(i)
        if isinstance(i[6], int):
            i[6] = _visual_json(i[6])
        _insert(conn, "inspection", _I, i)
    conn.commit()


def main(argv):
    path = config.db_path()
    if "--if-missing" in argv and path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = db.connect(path)
    try:
        seed(conn)
    finally:
        conn.close()
    print(f"База заполнена демо-данными: {path}")


if __name__ == "__main__":
    main(sys.argv[1:])
